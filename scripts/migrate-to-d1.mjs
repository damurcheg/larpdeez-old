// One-off migration script: local data/platform.db (better-sqlite3) -> Cloudflare D1.
//
// Usage:
//   node scripts/migrate-to-d1.mjs                     # writes ./migrations/seed.sql (offline preview)
//   npx wrangler d1 execute edu-platform --local  --file=./migrations/seed.sql
//   npx wrangler d1 execute edu-platform --remote --file=./migrations/seed.sql
//
// The source database is opened READ-ONLY and is never modified. Take a backup copy first:
//   cp data/platform.db data/platform.backup.db
//
// NOTE on passwords: the local server hashed with scrypt, which does not exist in the
// Workers runtime. The migrated passwordHash cannot be verified in production; after the
// first login set PLATFORM_PASSWORD once (or use the reset command below), then remove it.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import Database from 'better-sqlite3';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const DB_PATH = process.argv[2] || path.join(ROOT, 'data', 'platform.db');
const OUT = process.argv[3] || path.join(ROOT, 'migrations', 'seed.sql');

if (!fs.existsSync(DB_PATH)) {
  console.error(`Source DB not found: ${DB_PATH}`);
  process.exit(1);
}

const esc = (s) => `'${String(s).replace(/'/g, "''")}'`;

const db = new Database(DB_PATH, { readonly: true });

const settings = db.prepare('SELECT key, value FROM settings').all();
const courses = db.prepare('SELECT id, doc, sort, updatedAt FROM courses ORDER BY sort ASC').all();
const events = db.prepare('SELECT id, doc, date, updatedAt FROM events ORDER BY date ASC').all();
db.close();

let sql = `-- Generated from ${path.relative(ROOT, DB_PATH)} at ${new Date().toISOString()}\n`;
sql += `-- Source counts: settings=${settings.length} courses=${courses.length} events=${events.length}\n\n`;

for (const s of settings) {
  if (s.key === 'sessionSecret') continue; // regenerated by Functions on demand
  const val = s.key === 'passwordHash' && String(s.value).startsWith('scrypt:')
    ? '' // legacy scrypt hash — unusable in Workers; force bootstrap via PLATFORM_PASSWORD
    : s.value;
  if (s.key === 'passwordHash' && val === '') {
    sql += `DELETE FROM settings WHERE key = 'passwordHash';\n`;
    continue;
  }
  sql += `INSERT INTO settings (key, value) VALUES (${esc(s.key)}, ${esc(val)})\n  ON CONFLICT(key) DO UPDATE SET value = excluded.value;\n`;
}
for (const c of courses) {
  sql += `INSERT INTO courses (id, doc, sort, updatedAt) VALUES (${esc(c.id)}, ${esc(c.doc)}, ${c.sort}, ${c.updatedAt})\n  ON CONFLICT(id) DO UPDATE SET doc = excluded.doc, sort = excluded.sort, updatedAt = excluded.updatedAt;\n`;
}
for (const e of events) {
  sql += `INSERT INTO events (id, doc, date, updatedAt) VALUES (${esc(e.id)}, ${esc(e.doc)}, ${esc(e.date)}, ${e.updatedAt})\n  ON CONFLICT(id) DO UPDATE SET doc = excluded.doc, date = excluded.date, updatedAt = excluded.updatedAt;\n`;
}

sql += `\n-- Verification queries (run after import):\n`;
sql += `-- SELECT COUNT(*) FROM courses;  -- expected: ${courses.length}\n`;
sql += `-- SELECT COUNT(*) FROM events;   -- expected: ${events.length}\n`;

fs.writeFileSync(OUT, sql);
console.log(`Wrote ${OUT}`);
console.log(`Records: settings=${settings.length}, courses=${courses.length}, events=${events.length}`);
if (settings.some((s) => s.key === 'passwordHash' && String(s.value).startsWith('scrypt:'))) {
  console.log('WARNING: legacy scrypt passwordHash detected — it was skipped. Set PLATFORM_PASSWORD secret, log in, change the password in Profile, then delete the secret.');
}
